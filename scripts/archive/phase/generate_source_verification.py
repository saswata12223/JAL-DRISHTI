def generate_source_verification_artifacts():
    df_src = pd.DataFrame(SOURCE_VERIFICATION_RECORDS)
    csv_file = THRESH_DIR / "phase4_source_level_verification.csv"
    json_file = THRESH_DIR / "phase4_source_level_verification.json"

    df_src.to_csv(csv_file, index=False, encoding="utf-8")

    manifest = {
        "title": "FlashFloodAI Phase 4 Source-Level Threshold Verification Manifest",
        "version": "4.3.0",
        "target_region": "Uttarakhand, India",
        "standards_authority": "Central Water Commission (CWC), Ministry of Jal Shakti, Government of India",
        "verification_summary": {
            "total_stations": 20,
            "total_threshold_records": 60,
            "exact_source_confirmed": int(df_src["exact_value_confirmed"].sum()),
            "partially_verified": int((df_src["verification_status"] == "PARTIALLY_VERIFIED").sum()),
            "unverified": int((df_src["verification_status"] == "UNVERIFIED").sum()),
            "conflicting": int((df_src["verification_status"] == "CONFLICTING").sum()),
            "source_unavailable": int((df_src["verification_status"] == "SOURCE_UNAVAILABLE").sum()),
        },
        "records": SOURCE_VERIFICATION_RECORDS,
    }

    with open(json_file, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print(f"Generated {csv_file} ({csv_file.stat().st_size:,} bytes, {len(df_src)} rows)")
    print(f"Generated {json_file} ({json_file.stat().st_size:,} bytes)")

if __name__ == "__main__":
    generate_source_verification_artifacts()
